-- The app's whole database. Safe to run more than once, and on a project that already
-- has the earlier events and buildings tables. Run with `npm run db:setup`.
--
-- Columns mirror what the server writes: times are ISO 8601 UTC text and categories, extra
-- and the club lists are JSON strings. Times use the "C" collation because the server
-- compares them as strings, which only works byte by byte.

CREATE OR REPLACE FUNCTION now_iso() RETURNS TEXT LANGUAGE sql STABLE AS $$
  SELECT to_char(now() AT TIME ZONE 'utc', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')
$$;

CREATE TABLE IF NOT EXISTS users (
  id             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email          TEXT    NOT NULL UNIQUE,
  password_hash  TEXT    NOT NULL,
  email_verified INTEGER NOT NULL DEFAULT 0,
  created_at     TEXT COLLATE "C" NOT NULL DEFAULT now_iso()
);

-- One-time codes emailed during registration (see server/email.js).
CREATE TABLE IF NOT EXISTS verification_codes (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id    INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash  TEXT    NOT NULL,
  expires_at BIGINT  NOT NULL, -- ms since epoch
  attempts   INTEGER NOT NULL DEFAULT 0
);

-- Logins (see server/sessionStore.js).
CREATE TABLE IF NOT EXISTS sessions (
  sid     TEXT   PRIMARY KEY,
  sess    TEXT   NOT NULL,
  expires BIGINT NOT NULL -- ms since epoch
);

-- Scraped from clubs.wusa.ca (see server/clubs/scrapeWusa.js).
-- categories / socials / associated_clubs / gallery are JSON arrays.
CREATE TABLE IF NOT EXISTS clubs (
  id                     INTEGER PRIMARY KEY, -- WUSA club id
  slug                   TEXT,
  name                   TEXT NOT NULL,
  acronym                TEXT,
  tagline                TEXT,
  description            TEXT,
  year_started           INTEGER,
  member_count           INTEGER,
  executive_count        INTEGER,
  logo_url               TEXT,
  email                  TEXT,
  wusa_active_this_term  INTEGER NOT NULL DEFAULT 0,
  current_term_name      TEXT,
  membership_and_meeting TEXT,
  activities             TEXT,
  other                  TEXT,
  categories             TEXT NOT NULL DEFAULT '[]',
  socials                TEXT NOT NULL DEFAULT '[]',
  associated_clubs       TEXT NOT NULL DEFAULT '[]',
  gallery                TEXT NOT NULL DEFAULT '[]',
  wusa_last_updated      TEXT,
  scraped_at             TEXT NOT NULL
);

-- Campus buildings from UW's map API (see server/events/importBuildings.js).
CREATE TABLE IF NOT EXISTS buildings (
  code       TEXT PRIMARY KEY,
  name       TEXT NOT NULL,
  alt_names  TEXT NOT NULL DEFAULT '[]',
  lat        DOUBLE PRECISION NOT NULL,
  lng        DOUBLE PRECISION NOT NULL,
  updated_at TEXT NOT NULL DEFAULT now_iso()
);

-- Imported events (see server/events/importEvents.js). id is "<source>:<source id>".
CREATE TABLE IF NOT EXISTS events (
  id            TEXT PRIMARY KEY,
  source        TEXT NOT NULL,      -- wusa | uwaterloo | athletics | club | student
  feed          TEXT,               -- sub-feed, e.g. "Engineering"
  title         TEXT NOT NULL,
  description   TEXT,
  start_at      TEXT COLLATE "C" NOT NULL,
  end_at        TEXT COLLATE "C",
  all_day       INTEGER NOT NULL DEFAULT 0,
  location      TEXT,               -- raw location text from the source
  building_code TEXT REFERENCES buildings(code),
  url           TEXT,
  image_url     TEXT,
  organizer     TEXT,
  categories    TEXT NOT NULL DEFAULT '[]',
  cost          TEXT,
  extra         TEXT NOT NULL DEFAULT '{}', -- source-specific fields
  imported_at   TEXT COLLATE "C" NOT NULL DEFAULT now_iso(),
  -- Student-run events created in the app (see server/events/hosted.js).
  host_user_id  INTEGER,
  capacity      INTEGER
);

